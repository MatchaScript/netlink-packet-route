#[test]
fn test_get_filter_pedit_eth_dst() {
    let expected = TcAction {
        tab: 1,
        attributes: vec![
            TcActionAttribute::Kind("pedit".to_string()),
            TcActionAttribute::Stats(vec![
                TcStats2::Basic(TcStatsBasic {
                    bytes: 1048,
                    packets: 17,
                }),
                TcStats2::BasicHw(TcStatsBasic {
                    bytes: 0,
                    packets: 0,
                }),
                TcStats2::Queue(TcStatsQueue {
                    qlen: 0,
                    backlog: 0,
                    drops: 0,
                    requeues: 0,
                    overlimits: 0,
                }),
            ]),
            TcActionAttribute::InHwCount(0),
            TcActionAttribute::Options(vec![
                TcActionOption::Pedit(pedit_eth_dst_keys_ex()),
                TcActionOption::Pedit(pedit_eth_dst_parms_ex()),
                TcActionOption::Pedit(TcActionPeditOption::Tm(Tcf {
                    install: 1055119,
                    lastuse: 290926,
                    expires: 0,
                    firstuse: 1054788,
                })),
            ]),
        ],
    };

    assert_eq!(
        expected,
        TcAction::parse(&NlaBuffer::new(&TC_ACTION_PEDIT_ETH_DST)).unwrap()
    );

    let mut buf = vec![0; expected.buffer_len()];

    expected.emit(&mut buf);

    assert_eq!(buf, TC_ACTION_PEDIT_ETH_DST);
}

#[test]
fn test_emit_pedit_eth_dst() {
    let options = vec![pedit_eth_dst_keys_ex(), pedit_eth_dst_parms_ex()];

    let mut buf = vec![0xff; options.as_slice().buffer_len()];

    options.as_slice().emit(&mut buf);

    assert_eq!(buf, TC_ACTION_PEDIT_ETH_DST_OPTIONS);
}

// Verify that [`TcPedit`] fails to parse a buffer with an invalid number of
// keys.
#[test]
fn test_tc_pedit_invalid_nkeys() {
    // TC pedit selector buffer layout:
    // |byte0 .. byte19|byte20|byte21|byte22|byte23|
    // |---------------|------|------|-------------|
    // |    generic    |nkeys |flags |     pad     |
    // |---------------|------|------|-------------|
    // |                   keys                    |
    // |                    ...                    |
    let buffer = [
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xff, 0x00, 0x00, 0x00,
    ];
    assert!(TcPedit::parse(&buffer).is_err());
}
